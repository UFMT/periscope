export type TranslationKey = keyof (typeof translations)['pt-BR'];

export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dict = translations[locale] || translations['pt-BR'];
  let text: string = dict[key] ?? translations['pt-BR'][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function translateNature(locale: Locale, natureKey: string | null | undefined): string {
  if (!natureKey) return '—';
  const map = NATURE_LABELS[locale] || NATURE_LABELS['pt-BR'];
  return map[natureKey] || natureKey;
}
